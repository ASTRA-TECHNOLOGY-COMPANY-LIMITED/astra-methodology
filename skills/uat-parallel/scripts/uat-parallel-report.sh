#!/usr/bin/env bash
# ASTRA /uat-parallel — merge per-case JSON into index.html + issues.md + session.json
# Usage: uat-parallel-report.sh <SESSION_DIR> <REPORT_TEMPLATE_HTML>
set -euo pipefail

SESSION_DIR="${1:?SESSION_DIR required}"
TEMPLATE="${2:?TEMPLATE path required}"
RESULTS_DIR="$SESSION_DIR/raw/results"

if [ ! -d "$RESULTS_DIR" ]; then
  echo "[uat-parallel] No results in $RESULTS_DIR — nothing to merge." >&2
  exit 1
fi

if ! command -v node >/dev/null 2>&1; then
  echo "[uat-parallel] node is required to merge results." >&2
  exit 2
fi

node - "$SESSION_DIR" "$TEMPLATE" "$RESULTS_DIR" <<'NODE'
const fs = require('fs');
const path = require('path');

const [SESSION_DIR, TEMPLATE, RESULTS_DIR] = process.argv.slice(2);

// i18n dictionary — embedded mirror of skills/user-test/references/i18n-strings.md.
// The SSoT file is documentation; the runtime values live here.
// Keep the two in sync when adding/changing strings.
// /uat-parallel uses M_ISSUES_REPORT_TITLE_PARALLEL (with "(parallel)" / "(병렬)"
// qualifier) instead of M_ISSUES_REPORT_TITLE, so a single glance at the header
// tells the reader whether the run was sequential (Chrome MCP) or parallel.
// M_DEV_HINT is intentionally absent here — the Playwright runner has no LLM
// in the loop to author per-failure hints.
const LANG = (() => {
  const raw = String(process.env.UAT_LANG || 'vi').toLowerCase();
  if (['vi', 'vie', 'vietnamese'].includes(raw)) return 'vi';
  if (['en', 'eng', 'english'].includes(raw)) return 'en';
  if (['ko', 'kor', 'korean'].includes(raw)) return 'ko';
  return 'vi';
})();

const I18N = {
  vi: {
    T_REPORT_TITLE: '📋 Báo cáo UAT',
    T_REPORT_SUBTITLE: 'Báo cáo kiểm thử người dùng cuối — Session',
    T_STARTED: '🕒 Bắt đầu',
    T_FINISHED: '🏁 Kết thúc',
    T_MODE: '⚙️ Chế độ',
    T_LABEL_TEST_CASES: 'Test Cases',
    T_LABEL_PASS: 'PASS',
    T_LABEL_FAIL: 'FAIL',
    T_LABEL_DURATION: 'Thời gian',
    T_HEADING_DETAILS: 'Chi tiết test cases',
    T_HEADING_ISSUES: 'Issues',
    T_EMPTY_NO_ISSUES: 'Không có lỗi nào trong session này.',
    T_SEE_DETAILS_AT: 'Xem chi tiết tại',
    T_ISSUES_WORD: 'lỗi',
    T_FOOTER_GENERATED: 'Sinh bởi ASTRA',
    T_STATUS_PASS: 'PASS',
    T_STATUS_FAIL: 'FAIL',
    T_STATUS_SKIPPED: 'SKIPPED',
    M_ISSUES_REPORT_TITLE_PARALLEL: '# Báo cáo UAT Issues (parallel)',
    M_SESSION: 'Session',
    M_CASES_RUN: 'Test Cases chạy',
    M_TOTAL_ISSUES: 'Tổng số lỗi',
