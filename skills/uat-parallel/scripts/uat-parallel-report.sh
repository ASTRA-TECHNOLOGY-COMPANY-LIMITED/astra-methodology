    T_HEADING_DETAILS: 'Test case details',
    T_HEADING_ISSUES: 'Issues',
    T_EMPTY_NO_ISSUES: 'No issues found in this session.',
    T_SEE_DETAILS_AT: 'See details at',
    T_ISSUES_WORD: 'issues',
    T_FOOTER_GENERATED: 'Generated by ASTRA',
    T_STATUS_PASS: 'PASS',
    T_STATUS_FAIL: 'FAIL',
    T_STATUS_SKIPPED: 'SKIPPED',
    M_ISSUES_REPORT_TITLE_PARALLEL: '# UAT Issues Report (parallel)',
    M_SESSION: 'Session',
    M_CASES_RUN: 'Test cases run',
    M_TOTAL_ISSUES: 'Total issues',
    M_ISSUE: 'Issue',
    M_TEST_CASE: 'Test Case',
    M_STEP: 'Step',
    M_EXPECTED: 'Expected',
    M_ACTUAL: 'Actual',
    M_SEVERITY_REASON: 'Reason for',
    M_SCREENSHOT: 'Screenshot',
    M_TRACE: 'Trace (Playwright)',
  },
  ko: {
    T_REPORT_TITLE: '📋 UAT 보고서',
    T_REPORT_SUBTITLE: '최종 사용자 수용 테스트 보고서 — 세션',
    T_STARTED: '🕒 시작',
    T_FINISHED: '🏁 종료',
    T_MODE: '⚙️ 모드',
    T_LABEL_TEST_CASES: '테스트 케이스',
    T_LABEL_PASS: 'PASS',
    T_LABEL_FAIL: 'FAIL',
    T_LABEL_DURATION: '소요 시간',
    T_HEADING_DETAILS: '테스트 케이스 상세',
    T_HEADING_ISSUES: '이슈',
    T_EMPTY_NO_ISSUES: '이 세션에서 발견된 이슈가 없습니다.',
    T_SEE_DETAILS_AT: '자세한 내용은 다음에서 확인하세요',
    T_ISSUES_WORD: '건의 이슈',
    T_FOOTER_GENERATED: 'ASTRA로 생성됨',
    T_STATUS_PASS: '통과',
    T_STATUS_FAIL: '실패',
    T_STATUS_SKIPPED: '건너뜀',
    M_ISSUES_REPORT_TITLE_PARALLEL: '# UAT 이슈 리포트 (병렬)',
    M_SESSION: '세션',
    M_CASES_RUN: '실행된 테스트 케이스',
    M_TOTAL_ISSUES: '전체 이슈 수',
    M_ISSUE: '이슈',
    M_TEST_CASE: '테스트 케이스',
    M_STEP: '단계',
    M_EXPECTED: '기대값',
    M_ACTUAL: '실제값',
    M_SEVERITY_REASON: '사유',
    M_SCREENSHOT: '스크린샷',
    M_TRACE: 'Trace (Playwright)',
